"""Build locally hosted Source Han Serif TW variable WOFF2 assets.

Usage: python build-source-han-fonts.py /path/to/SourceHanSerifTW-VF.ttf
Requires fonttools[woff]==4.66.1. The normal site build uses committed files.
"""
from pathlib import Path
import hashlib, json, sys
from fontTools.ttLib import TTFont
from fontTools.subset import Options, Subsetter

root = Path(__file__).resolve().parent.parent
source = Path(sys.argv[1])
font = TTFont(source)
cmap = set(font.getBestCmap())
weights = next(axis for axis in font['fvar'].axes if axis.axisTag == 'wght')
# Core includes current UI and published treatment vocabulary. Remaining source
# glyphs stay available in disjoint, on-demand ranges for future catalogue text.
text = ''.join(p.read_text() for p in (root / 'src').rglob('*') if p.suffix in {'.js', '.jsx', '.css'})
text += '苦茶籽潔淨髮浴森呼吸柔禾角質調理墨玉烏60天木質萃湯浴薑暖陽鮮薑溫通舒筋'
core = ({ord(c) for c in text} | set(range(0x20, 0x250)) | set(range(0x2000, 0x2070))) & cmap
remaining = sorted(cmap - core)
groups = [('core', sorted(core))] + [(f'{i//512:02d}', remaining[i:i+512]) for i in range(0, len(remaining), 512)]
out = root / 'public/fonts'
manifest, css = {}, ["/* Generated by scripts/build-source-han-fonts.py; do not edit ranges. */"]
def ranges(points):
    spans, start, end = [], points[0], points[0]
    for cp in points[1:]:
        if cp == end + 1: end = cp
        else:
            spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
            start = end = cp
    spans.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ','.join(spans)
source_hash = hashlib.sha256(source.read_bytes()).hexdigest()
for group, points in groups:
    part = TTFont(source)
    options = Options()
    options.layout_features = ['*']
    subset = Subsetter(options=options)
    subset.populate(unicodes=points)
    subset.subset(part)
    part.flavor = 'woff2'
    name = f'rou-songti-tc-{group}-v1.woff2'
    # Subsetting is a modification: use a distinct internal name under OFL.
    for record in part['name'].names:
        if record.nameID in (1, 3, 4, 6, 16, 25):
            value = 'ROUSongtiTC' if record.nameID in (3, 6, 25) else 'ROU Songti TC'
            record.string = value.encode(record.getEncoding())
        elif record.nameID >= 256 and 'SourceHanSerif' in record.toUnicode():
            record.string = record.toUnicode().replace('SourceHanSerifTWVF', 'ROUSongtiTC').encode(record.getEncoding())
    part.save(out / name)
    data = (out / name).read_bytes()
    manifest[name] = {'sha256': hashlib.sha256(data).hexdigest(), 'source_sha256': source_hash,
      'source': 'https://github.com/adobe-fonts/source-han-serif/blob/7889f11bf31170b5d092a083b357c8c8130f89e0/Variable/TTF/Subset/SourceHanSerifTW-VF.ttf',
      'bytes': len(data), 'codepoints': points, 'weight': [weights.minValue, weights.maxValue]}
    css.append(f"@font-face{{font-family:'ROU Songti TC';src:url('/fonts/{name}') format('woff2');font-weight:{weights.minValue:g} {weights.maxValue:g};font-style:normal;font-display:swap;unicode-range:{ranges(points)};}}")
    print(group, len(points), len(data), flush=True)
(out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
(root / 'src/source-han-fonts.css').write_text('\n'.join(css) + '\n')
print('Covered all official Taiwan source codepoints:', len(cmap), flush=True)
