import assert from 'node:assert/strict';
import {bookingMatchesContext as booking, reviewMatchesContext as review} from '../src/lib/operations-navigation.js';
const row={status:'in_service',staff_id:'a',room_id:'bed1',starts_at:'2026-10-08T10:00:00+08:00',ends_at:'2026-10-08T10:45:00+08:00',blocked_until:'2026-10-08T11:00:00+08:00'};
let checks=0;const check=(actual,expected)=>{assert.equal(actual,expected);checks++;};
check(booking(row,null),true);
check(booking(row,{status:'pending'}),false);
check(booking(row,{statuses:['checked_in','in_service']}),true);
check(booking(row,{staff_id:'b'}),false);
check(booking(row,{room_id:'bed2'}),false);
check(booking(row,{room_id:'bed1',staff_id:'a'}),true);
check(booking({...row,status:'completed'},{unsettled:true}),true);
check(booking({...row,status:'completed',checkout:{id:'x'}},{unsettled:true}),false);
check(booking(row,{ends_before:'2026-10-08T02:45:00Z'}),true);
check(booking(row,{ends_before:'2026-10-08T02:44:59Z'}),false);
check(booking(row,{starts_before:'2026-10-08T02:00:00Z',ends_after:'2026-10-08T02:15:00Z'}),true);
check(booking(row,{ends_after:'2026-10-08T02:45:00Z'}),false);
check(booking(row,{blocked_after:'2026-10-08T02:50:00Z'}),true);
check(booking(row,{blocked_after:'2026-10-08T03:00:00Z'}),false);
const context={status:'pending',from:'2026-10-09',to:'2026-10-09'};
check(review({status:'pending',created_at:'2026-10-08T16:01:00Z'},context),true);
check(review({status:'pending',created_at:'2026-10-08T15:59:00Z'},context),false);
check(review({status:'published',created_at:'2026-10-08T16:01:00Z'},context),false);
console.log(`Operations navigation checks passed: ${checks}`);
