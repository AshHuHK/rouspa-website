import assert from 'node:assert/strict';
import { createOperationsRpc, readSessionWithDeadline } from '../src/lib/operations-rpc.js';
import { unwrapRpcResult, isInvalidSession } from '../src/lib/rpc-result.js';
import { createPublicRpc } from '../src/lib/public-rpc.js';

let checks=0;
const check=(value,label)=>{assert.ok(value,label);checks++;};
const reject=async(action,pattern)=>{await assert.rejects(action,pattern);checks++;};
const calls=[];
const client={rpc:(name,args)=>({abortSignal(signal){calls.push({name,args,signal});return Promise.resolve({data:{id:'same-result'},error:null});}})};
const rpc=createOperationsRpc(client,{timeoutMs:50});
const args={p_request:'same-operation',p_cents:10000};
check((await rpc('spa_topup',args)).id==='same-result','successful operation reaches its caller');
await rpc('spa_topup',args);
check(calls.length===2&&calls.every(call=>call.args.p_request==='same-operation'),'caller request IDs remain unchanged across explicit retries');
check(calls.every(call=>!call.signal.aborted),'finished operations clear their deadlines');
const structured=createOperationsRpc({rpc:async()=>({data:{error:'CUSTOMER_IDENTITY_INVALID'},error:null})});
await reject(()=>structured('spa_create_booking'),/CUSTOMER_IDENTITY_INVALID/);
const denied={code:'PGRST301',message:'No suitable key or wrong key type'};
await reject(()=>createOperationsRpc({rpc:async()=>({data:null,error:denied})})('spa_session'),error=>error===denied);
check(isInvalidSession(denied)&&isInvalidSession({message:'JWT expired'}),'invalid credentials are recognized for controlled re-login');
check(!isInvalidSession({message:'OPERATIONS_REQUEST_TIMEOUT'})&&!isInvalidSession({message:'FORBIDDEN'}),'temporary failures and business permissions do not automatically invalidate credentials');
let signal;
const stalled=createOperationsRpc({rpc:()=>({abortSignal(value){signal=value;return new Promise(()=>{});}})},{timeoutMs:10});
await reject(()=>stalled('spa_expense',{p_request:'retain-after-timeout'}),/OPERATIONS_REQUEST_TIMEOUT/);
check(signal.aborted,'stalled network is aborted and saving UI can settle');
await reject(()=>createOperationsRpc({rpc:()=>new Promise(()=>{})},{timeoutMs:10})('spa_session'),/OPERATIONS_REQUEST_TIMEOUT/);
await reject(()=>createOperationsRpc({rpc:()=>Promise.reject(new TypeError('Failed to fetch'))})('spa_session'),/OPERATIONS_NETWORK_ERROR/);
check(unwrapRpcResult(null)===null&&unwrapRpcResult([]).length===0,'void and collection RPCs keep their shapes');
await reject(()=>Promise.resolve().then(()=>unwrapRpcResult({error:'RATE_LIMIT'})),/RATE_LIMIT/);
const directPublic=createPublicRpc({url:'https://audit.invalid',key:'public-test',fetchImpl:async()=>new Response(JSON.stringify({error:'RATE_LIMIT'}))});
await reject(()=>directPublic('spa_member_login'),/RATE_LIMIT/);
check(await readSessionWithDeadline({getSession:async()=>({data:{session:null},error:null})})===null,'no session remains a legitimate signed-out state');
const session={user:{id:'audit-only'}};
check(await readSessionWithDeadline({getSession:async()=>({data:{session},error:null})})===session,'existing session remains available');
await reject(()=>readSessionWithDeadline({getSession:()=>new Promise(()=>{})},10),/OPERATIONS_REQUEST_TIMEOUT/);
await reject(()=>readSessionWithDeadline({getSession:async()=>({data:{session:null},error:denied})}),error=>error===denied);
console.log(`Operations connection and recovery checks passed: ${checks}`);
